-- Zameel 029: runtime repair for durable WebRTC signaling + schema-compatible story engagement.
-- Safe to run after the existing Zameel migrations. This migration is idempotent.

begin;

-- ---------------------------------------------------------------------------
-- 1) Durable direct-call signaling
-- ---------------------------------------------------------------------------
create table if not exists public.direct_call_sessions (
  room_id text primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  caller_id uuid not null references public.users(id) on delete cascade,
  callee_id uuid not null references public.users(id) on delete cascade,
  with_video boolean not null default true,
  status text not null default 'ringing' check (status in ('ringing','active','ended','declined')),
  created_at timestamptz not null default now(),
  answered_at timestamptz,
  ended_at timestamptz,
  check (caller_id <> callee_id)
);

create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  room_id text not null references public.direct_call_sessions(room_id) on delete cascade,
  sender_id uuid not null references public.users(id) on delete cascade,
  payload jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists call_signals_room_created_idx
  on public.call_signals(room_id, created_at, id);

alter table public.direct_call_sessions enable row level security;
alter table public.call_signals enable row level security;

drop policy if exists direct_call_sessions_member_select on public.direct_call_sessions;
create policy direct_call_sessions_member_select
on public.direct_call_sessions for select to authenticated
using (auth.uid() = caller_id or auth.uid() = callee_id);

drop policy if exists direct_call_sessions_member_update on public.direct_call_sessions;
create policy direct_call_sessions_member_update
on public.direct_call_sessions for update to authenticated
using (auth.uid() = caller_id or auth.uid() = callee_id)
with check (auth.uid() = caller_id or auth.uid() = callee_id);

drop policy if exists call_signals_member_select on public.call_signals;
create policy call_signals_member_select
on public.call_signals for select to authenticated
using (
  exists (
    select 1
    from public.direct_call_sessions s
    where s.room_id = call_signals.room_id
      and auth.uid() in (s.caller_id, s.callee_id)
  )
);

drop policy if exists call_signals_member_insert on public.call_signals;
create policy call_signals_member_insert
on public.call_signals for insert to authenticated
with check (
  sender_id = auth.uid()
  and exists (
    select 1
    from public.direct_call_sessions s
    where s.room_id = call_signals.room_id
      and auth.uid() in (s.caller_id, s.callee_id)
      and s.status <> 'ended'
  )
);

-- ---------------------------------------------------------------------------
-- 2) Story view schema compatibility
--    Existing deployments may use viewer_id OR user_id. The Flutter client now
--    calls RPCs below, so it never needs to assume either physical column name.
-- ---------------------------------------------------------------------------
create table if not exists public.story_views (
  story_id uuid not null references public.social_stories(id) on delete cascade,
  viewer_id uuid references public.users(id) on delete cascade,
  viewed_at timestamptz not null default now()
);

create table if not exists public.story_reactions (
  story_id uuid not null references public.social_stories(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  reaction text not null default '❤️',
  created_at timestamptz not null default now(),
  primary key (story_id, user_id)
);

alter table public.story_views add column if not exists viewed_at timestamptz default now();
update public.story_views set viewed_at = now() where viewed_at is null;

alter table public.story_views enable row level security;
alter table public.story_reactions enable row level security;

-- Keep direct-table policies valid for old application builds too. The RPCs
-- themselves use SECURITY DEFINER after explicit ownership/auth checks.
do $$
declare
  has_viewer_id boolean;
  has_user_id boolean;
begin
  select exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='story_views' and column_name='viewer_id'
  ) into has_viewer_id;
  select exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='story_views' and column_name='user_id'
  ) into has_user_id;

  if not has_viewer_id and not has_user_id then
    alter table public.story_views add column viewer_id uuid references public.users(id) on delete cascade;
    has_viewer_id := true;
  end if;

  if has_viewer_id then
    execute 'create unique index if not exists story_views_story_viewer_compat_uidx on public.story_views(story_id, viewer_id) where viewer_id is not null';
  end if;
  if has_user_id then
    execute 'create unique index if not exists story_views_story_user_compat_uidx on public.story_views(story_id, user_id) where user_id is not null';
  end if;
end $$;

-- Record a view using whichever deployed identity column exists.
create or replace function public.record_story_view_compat(p_story_id uuid)
returns void
language plpgsql
security definer
set search_path = public
set row_security = off
as $$
declare
  me uuid := auth.uid();
  owner_id uuid;
  has_viewer_id boolean;
  has_user_id boolean;
begin
  if me is null then
    raise exception 'not_authenticated';
  end if;

  select s.user_id into owner_id
  from public.social_stories s
  where s.id = p_story_id
    and s.expires_at > now();

  if owner_id is null then
    return;
  end if;
  if owner_id = me then
    return;
  end if;

  select exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='story_views' and column_name='viewer_id'
  ) into has_viewer_id;
  select exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='story_views' and column_name='user_id'
  ) into has_user_id;

  if has_viewer_id and has_user_id then
    execute $q$
      insert into public.story_views(story_id, viewer_id, user_id, viewed_at)
      values ($1, $2, $2, now())
      on conflict do nothing
    $q$ using p_story_id, me;
    execute 'update public.story_views set viewed_at = now() where story_id = $1 and (viewer_id = $2 or user_id = $2)'
      using p_story_id, me;
  elsif has_viewer_id then
    execute $q$
      insert into public.story_views(story_id, viewer_id, viewed_at)
      values ($1, $2, now())
      on conflict do nothing
    $q$ using p_story_id, me;
    execute 'update public.story_views set viewed_at = now() where story_id = $1 and viewer_id = $2'
      using p_story_id, me;
  elsif has_user_id then
    execute $q$
      insert into public.story_views(story_id, user_id, viewed_at)
      values ($1, $2, now())
      on conflict do nothing
    $q$ using p_story_id, me;
    execute 'update public.story_views set viewed_at = now() where story_id = $1 and user_id = $2'
      using p_story_id, me;
  else
    raise exception 'story_views has no viewer identity column';
  end if;
end;
$$;

-- Return viewers only to the story owner. Dynamic SQL avoids referencing a
-- column that might not physically exist in a legacy deployment.
create or replace function public.get_story_viewers_compat(p_story_id uuid)
returns table(
  user_id uuid,
  name text,
  profile_image text,
  viewed_at timestamptz
)
language plpgsql
security definer
set search_path = public
set row_security = off
as $$
declare
  me uuid := auth.uid();
  owner_id uuid;
  has_viewer_id boolean;
  has_user_id boolean;
begin
  if me is null then
    raise exception 'not_authenticated';
  end if;

  select s.user_id into owner_id from public.social_stories s where s.id = p_story_id;
  if owner_id is distinct from me then
    raise exception 'story_owner_required';
  end if;

  select exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='story_views' and column_name='viewer_id'
  ) into has_viewer_id;
  select exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='story_views' and column_name='user_id'
  ) into has_user_id;

  if has_viewer_id then
    return query execute $q$
      select u.id, coalesce(u.name, 'زميل')::text, u.profile_image::text, max(v.viewed_at)::timestamptz
      from public.story_views v
      join public.users u on u.id = v.viewer_id
      where v.story_id = $1 and v.viewer_id is not null
      group by u.id, u.name, u.profile_image
      order by max(v.viewed_at) desc
    $q$ using p_story_id;
  elsif has_user_id then
    return query execute $q$
      select u.id, coalesce(u.name, 'زميل')::text, u.profile_image::text, max(v.viewed_at)::timestamptz
      from public.story_views v
      join public.users u on u.id = v.user_id
      where v.story_id = $1 and v.user_id is not null
      group by u.id, u.name, u.profile_image
      order by max(v.viewed_at) desc
    $q$ using p_story_id;
  end if;
end;
$$;

create or replace function public.get_story_reactions_compat(p_story_id uuid)
returns table(
  user_id uuid,
  name text,
  profile_image text,
  reaction text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public
set row_security = off
as $$
declare
  me uuid := auth.uid();
  owner_id uuid;
begin
  if me is null then
    raise exception 'not_authenticated';
  end if;

  select s.user_id into owner_id from public.social_stories s where s.id = p_story_id;
  if owner_id is distinct from me then
    raise exception 'story_owner_required';
  end if;

  return query
    select r.user_id, coalesce(u.name, 'زميل')::text, u.profile_image::text,
           r.reaction::text, r.created_at
    from public.story_reactions r
    join public.users u on u.id = r.user_id
    where r.story_id = p_story_id
    order by r.created_at desc;
end;
$$;

revoke execute on function public.record_story_view_compat(uuid) from public, anon;
revoke execute on function public.get_story_viewers_compat(uuid) from public, anon;
revoke execute on function public.get_story_reactions_compat(uuid) from public, anon;
grant execute on function public.record_story_view_compat(uuid) to authenticated;
grant execute on function public.get_story_viewers_compat(uuid) to authenticated;
grant execute on function public.get_story_reactions_compat(uuid) to authenticated;

-- Preserve direct policies for reactions and allow a story owner to read all
-- reactions on their own story.
drop policy if exists story_reactions_member_access on public.story_reactions;
create policy story_reactions_member_access
on public.story_reactions for select to authenticated
using (
  user_id = auth.uid()
  or exists (
    select 1 from public.social_stories s
    where s.id = story_reactions.story_id and s.user_id = auth.uid()
  )
);

drop policy if exists story_reactions_self_insert on public.story_reactions;
create policy story_reactions_self_insert
on public.story_reactions for insert to authenticated
with check (user_id = auth.uid());

drop policy if exists story_reactions_self_update on public.story_reactions;
create policy story_reactions_self_update
on public.story_reactions for update to authenticated
using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists story_reactions_self_delete on public.story_reactions;
create policy story_reactions_self_delete
on public.story_reactions for delete to authenticated
using (user_id = auth.uid());

