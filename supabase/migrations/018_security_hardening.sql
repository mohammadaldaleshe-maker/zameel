-- ---------------------------------------------------------------------------
-- Graduation invite_token is a bearer secret. It must never be returned by a
-- normal select on a public graduation book.
-- ---------------------------------------------------------------------------
revoke select (invite_token) on table public.graduation_books from anon, authenticated;

create or replace function public.get_graduation_book_invite_token(p_book_id uuid)
returns text
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_token text;
  v_owner uuid;
begin
  if auth.uid() is null then
    raise exception 'not_authenticated';
  end if;

  select owner_id, invite_token
    into v_owner, v_token
  from public.graduation_books
  where id = p_book_id;

  if v_owner is null then
    raise exception 'book_not_found';
  end if;
  if v_owner <> auth.uid() then
    raise exception 'owner_only';
  end if;

  return v_token;
end;
$$;
revoke execute on function public.get_graduation_book_invite_token(uuid) from public, anon;
grant execute on function public.get_graduation_book_invite_token(uuid) to authenticated;

-- Invite joins must also respect blocking, while keeping the invitation feature.
create or replace function public.join_graduation_book(p_book_id uuid, p_token text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_owner uuid;
  v_ok boolean;
begin
  if v_uid is null then raise exception 'not_authenticated'; end if;

  select owner_id, (is_public and allow_writes and invite_token = p_token)
    into v_owner, v_ok
  from public.graduation_books
  where id = p_book_id;

  if coalesce(v_ok, false) = false then
    return false;
  end if;
  if v_owner = v_uid then
    return true;
  end if;
  if public.is_blocked(v_uid, v_owner) then
    raise exception 'blocked_user';
  end if;

  insert into public.graduation_book_members(book_id, user_id)
  values (p_book_id, v_uid)
  on conflict do nothing;

  perform public.ensure_graduation_book_member_pages(p_book_id);
  return true;
end;
$$;
revoke execute on function public.join_graduation_book(uuid,text) from public, anon;
grant execute on function public.join_graduation_book(uuid,text) to authenticated;

-- ---------------------------------------------------------------------------
-- Notifications are server-generated by trusted triggers. Clients may read,
-- mark read and delete their own notifications, but may not forge events for
-- arbitrary recipients.
-- ---------------------------------------------------------------------------
drop policy if exists notifications_insert_authenticated on public.notifications;
revoke insert on table public.notifications from authenticated, anon;

-- ---------------------------------------------------------------------------
-- Post interaction authorization: a user cannot manufacture likes/saves/
-- comments against a private or blocked post by guessing its UUID.
-- ---------------------------------------------------------------------------
drop policy if exists likes_select_authenticated on public.likes;
drop policy if exists likes_insert_self on public.likes;
create policy likes_select_authenticated
on public.likes for select to authenticated
using (public.can_view_post(auth.uid(), post_id));
create policy likes_insert_self
on public.likes for insert to authenticated
with check (user_id = auth.uid() and public.can_view_post(auth.uid(), post_id));

-- Keep self-delete behavior intact.

 drop policy if exists saved_posts_insert_self on public.saved_posts;
create policy saved_posts_insert_self
on public.saved_posts for insert to authenticated
with check (user_id = auth.uid() and public.can_view_post(auth.uid(), post_id));

-- Comments must follow the same visibility as the source post.
drop policy if exists post_comments_select_authenticated on public.post_comments;
drop policy if exists post_comments_insert_self on public.post_comments;
