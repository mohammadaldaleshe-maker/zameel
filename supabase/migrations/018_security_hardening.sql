-- ---------------------------------------------------------------------------
-- Blocking: stop new follows and direct member injection across a block.
-- Existing relationships are preserved; no feature/data is deleted.
-- ---------------------------------------------------------------------------
drop policy if exists follows_insert_self on public.follows;
create policy follows_insert_self
on public.follows for insert to authenticated
with check (
  follower_id = auth.uid()
  and following_id <> auth.uid()
  and not public.is_blocked(auth.uid(), following_id)
);

-- A blocked participant cannot be added to a conversation by the creator.
drop policy if exists conversation_members_self_insert on public.conversation_members;
create policy conversation_members_self_insert
on public.conversation_members for insert to authenticated
with check (
  (
    user_id = auth.uid()
    and exists (
      select 1 from public.conversations c
      where c.id = conversation_id and c.created_by = auth.uid()
    )
  )
  or (
    user_id <> auth.uid()
    and exists (
      select 1 from public.conversations c
      where c.id = conversation_id and c.created_by = auth.uid()
    )
    and not public.is_blocked(auth.uid(), user_id)
  )
);

