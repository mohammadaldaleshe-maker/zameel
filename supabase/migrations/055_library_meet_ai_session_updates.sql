-- Meet-a-colleague: a new pending request may be sent every 15 seconds.
-- Accepted sessions remain exclusive until either user closes them or the
-- clients detect that both users have physically met and mark them complete.
create or replace function public.request_meet_colleague(
  target_conversation_id uuid,
  target_recipient_id uuid,
  my_lat double precision,
  my_lng double precision
) returns uuid
language plpgsql security definer set search_path=public set row_security=off as $$
declare
  me uuid:=auth.uid();
  new_id uuid;
  latest_pending public.meet_colleague_requests;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  if my_lat not between -90 and 90 or my_lng not between -180 and 180 then
    raise exception 'invalid_location';
  end if;
  if not exists(
      select 1 from public.conversation_members
      where conversation_id=target_conversation_id and user_id=me
    ) or not exists(
      select 1 from public.conversation_members
      where conversation_id=target_conversation_id and user_id=target_recipient_id
    ) then
    raise exception 'conversation_membership_required';
  end if;

  update public.meet_colleague_requests
     set status='expired', responded_at=coalesce(responded_at,now())
   where conversation_id=target_conversation_id
     and status in('pending','accepted')
     and expires_at<=now();

  if exists(
    select 1 from public.meet_colleague_requests
    where conversation_id=target_conversation_id
      and status='accepted' and expires_at>now()
  ) then
    raise exception 'active_meet_session_exists';
  end if;

  select * into latest_pending
  from public.meet_colleague_requests
  where conversation_id=target_conversation_id
    and status='pending' and expires_at>now()
  order by created_at desc limit 1;

  if latest_pending.id is not null then
    if latest_pending.created_at > now()-interval '15 seconds' then
      raise exception 'meet_request_retry_after_15_seconds';
    end if;
    update public.meet_colleague_requests
       set status='expired', responded_at=coalesce(responded_at,now())
     where conversation_id=target_conversation_id and status='pending';
  end if;

  insert into public.meet_colleague_requests(
    conversation_id,requester_id,recipient_id,requester_lat,requester_lng
  ) values(
    target_conversation_id,me,target_recipient_id,my_lat,my_lng
  ) returning id into new_id;

  insert into public.notifications(
    user_id,actor_id,type,title_ar,title_en,body_ar,body_en,data,is_read
  ) values(
    target_recipient_id,me,'meet_colleague_request',
    'طلب «التقِ بزميل»','Meet a colleague request',
    'يريد زميلك مشاركة موقع مؤقت للالتقاء بك',
    'Your colleague wants to share temporary locations to meet',
    jsonb_build_object('meet_request_id',new_id,'conversation_id',target_conversation_id),false
  );
  return new_id;
end $$;

-- Include created_at so the client can display/enforce the 15-second resend cooldown.
drop function if exists public.get_active_meet_colleague(uuid);
create function public.get_active_meet_colleague(target_conversation_id uuid)
returns table(
  request_id uuid,requester_id uuid,recipient_id uuid,status text,
  requester_lat double precision,requester_lng double precision,
  recipient_lat double precision,recipient_lng double precision,
  meeting_lat double precision,meeting_lng double precision,
  requester_updated_at timestamptz,recipient_updated_at timestamptz,
  created_at timestamptz,expires_at timestamptz
)
language sql security definer set search_path=public set row_security=off as $$
  select m.id,m.requester_id,m.recipient_id,m.status,
         m.requester_lat,m.requester_lng,m.recipient_lat,m.recipient_lng,
         m.meeting_lat,m.meeting_lng,m.requester_updated_at,m.recipient_updated_at,
         m.created_at,m.expires_at
  from public.meet_colleague_requests m
  where m.conversation_id=target_conversation_id
    and auth.uid() in(m.requester_id,m.recipient_id)
    and m.status in('pending','accepted') and m.expires_at>now()
  order by m.created_at desc limit 1;
$$;

revoke execute on function public.request_meet_colleague(uuid,uuid,double precision,double precision),
  public.get_active_meet_colleague(uuid) from public,anon;
grant execute on function public.request_meet_colleague(uuid,uuid,double precision,double precision),
  public.get_active_meet_colleague(uuid) to authenticated;

