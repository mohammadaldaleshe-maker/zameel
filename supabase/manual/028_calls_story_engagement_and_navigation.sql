-- Zameel 028: reliable direct-call signaling + synchronized hangup + story engagement policies.
-- Safe to run after 027_messages_sender_fk_and_call_signaling.sql.

begin;

create table if not exists public.direct_call_sessions (
  room_id text primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  caller_id uuid not null references public.users(id) on delete cascade,
  callee_id uuid not null references public.users(id) on delete cascade,
  with_video boolean not null default true,
  status text not null default 'ringing' check (status in ('ringing','active','ended','declined')),
  created_at timestamptz not null default now(),
  answered_at timestamptz,
  ended_at timestamptz,
  check (caller_id <> callee_id)
);

create index if not exists direct_call_sessions_members_idx
  on public.direct_call_sessions(caller_id, callee_id, created_at desc);

create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  room_id text not null references public.direct_call_sessions(room_id) on delete cascade,
  sender_id uuid not null references public.users(id) on delete cascade,
  payload jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists call_signals_room_created_idx
  on public.call_signals(room_id, created_at);

alter table public.direct_call_sessions enable row level security;
alter table public.call_signals enable row level security;

drop policy if exists direct_call_sessions_member_select on public.direct_call_sessions;
create policy direct_call_sessions_member_select
on public.direct_call_sessions for select to authenticated
using (auth.uid() = caller_id or auth.uid() = callee_id);

drop policy if exists direct_call_sessions_member_update on public.direct_call_sessions;
create policy direct_call_sessions_member_update
on public.direct_call_sessions for update to authenticated
using (auth.uid() = caller_id or auth.uid() = callee_id)
with check (auth.uid() = caller_id or auth.uid() = callee_id);

drop policy if exists call_signals_member_select on public.call_signals;
create policy call_signals_member_select
on public.call_signals for select to authenticated
using (
  exists (
    select 1 from public.direct_call_sessions s
    where s.room_id = call_signals.room_id
      and auth.uid() in (s.caller_id, s.callee_id)
  )
);

drop policy if exists call_signals_member_insert on public.call_signals;
create policy call_signals_member_insert
on public.call_signals for insert to authenticated
with check (
  sender_id = auth.uid()
  and exists (
    select 1 from public.direct_call_sessions s
    where s.room_id = call_signals.room_id
      and auth.uid() in (s.caller_id, s.callee_id)
      and s.status <> 'ended'
  )
);

-- Normalize legacy story_views schemas before installing policies.
-- Some deployed Zameel databases use user_id instead of viewer_id.
do $$
declare
  has_viewer_id boolean;
  has_user_id boolean;
begin
  select exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'story_views' and column_name = 'viewer_id'
  ) into has_viewer_id;

  select exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'story_views' and column_name = 'user_id'
  ) into has_user_id;

  if not has_viewer_id then
    alter table public.story_views add column viewer_id uuid;
    if has_user_id then
      update public.story_views
      set viewer_id = user_id
      where viewer_id is null;
    end if;
  end if;

  -- Keep the FK name stable because the Flutter query uses it as a PostgREST hint.
  if not exists (
    select 1
    from pg_constraint c
    join pg_class t on t.oid = c.conrelid
    join pg_namespace n on n.oid = t.relnamespace
    where n.nspname = 'public'
      and t.relname = 'story_views'
      and c.conname = 'story_views_viewer_id_fkey'
  ) then
    alter table public.story_views
      add constraint story_views_viewer_id_fkey
      foreign key (viewer_id) references public.users(id) on delete cascade not valid;
    alter table public.story_views validate constraint story_views_viewer_id_fkey;
  end if;

  if not exists (select 1 from public.story_views where viewer_id is null) then
    alter table public.story_views alter column viewer_id set not null;
  end if;

  create unique index if not exists story_views_story_viewer_uidx
    on public.story_views(story_id, viewer_id);
end $$;

-- If this is the legacy schema, mirror user_id <-> viewer_id so both old and
-- new application builds continue to work during the transition.
do $$
declare
  has_user_id boolean;
begin
  select exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'story_views' and column_name = 'user_id'
  ) into has_user_id;

  if has_user_id then
    execute $fn$
      create or replace function public.zameel_sync_story_view_user_ids()
      returns trigger
      language plpgsql
      set search_path = public
      as $body$
      begin
        if new.viewer_id is null then
          new.viewer_id := new.user_id;
        end if;
        if new.user_id is null then
          new.user_id := new.viewer_id;
        end if;
        if new.viewer_id is distinct from new.user_id then
          new.user_id := new.viewer_id;
        end if;
        return new;
      end;
      $body$;
    $fn$;

    drop trigger if exists zameel_story_views_sync_ids on public.story_views;
    create trigger zameel_story_views_sync_ids
      before insert or update on public.story_views
      for each row execute function public.zameel_sync_story_view_user_ids();
  end if;
end $$;

