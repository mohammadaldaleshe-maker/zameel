-- Rebuild direct-call RPC so every invitation creates its durable session before
-- the notification can be delivered.
drop function if exists public.start_direct_call(uuid, uuid, text, boolean);
create function public.start_direct_call(
  other_user_id uuid,
  target_conversation_id uuid,
  target_room_id text,
  with_video boolean default true
)
returns uuid
language plpgsql
security definer
set search_path = public
set row_security = off
as $$
declare
  me uuid := auth.uid();
  caller_name text;
  notification_id uuid;
  allowed boolean;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  if other_user_id is null or other_user_id = me then raise exception 'invalid_partner'; end if;
  if target_conversation_id is null or coalesce(trim(target_room_id), '') = '' then raise exception 'invalid_call_room'; end if;
  if not public.is_conversation_member(target_conversation_id, me)
     or not public.is_conversation_member(target_conversation_id, other_user_id) then
    raise exception 'conversation_membership_required';
  end if;
  if public.is_blocked(me, other_user_id) then raise exception 'blocked_user'; end if;
  if not public.is_colleague(me, other_user_id) then raise exception 'colleague_only'; end if;

  select coalesce(u.allow_calls, true) into allowed from public.users u where u.id = other_user_id;
  if coalesce(allowed, false) = false then raise exception 'calls_disabled'; end if;
  select coalesce(nullif(u.name, ''), 'زميل') into caller_name from public.users u where u.id = me;

  insert into public.direct_call_sessions(room_id, conversation_id, caller_id, callee_id, with_video, status)
  values (target_room_id, target_conversation_id, me, other_user_id, with_video, 'ringing')
  on conflict (room_id) do update set
    conversation_id = excluded.conversation_id,
    caller_id = excluded.caller_id,
    callee_id = excluded.callee_id,
    with_video = excluded.with_video,
    status = 'ringing',
    created_at = now(),
    answered_at = null,
    ended_at = null;

  insert into public.notifications(user_id, actor_id, type, title_ar, title_en, body_ar, body_en, data, is_read)
  values (
    other_user_id, me,
    case when with_video then 'incoming_video_call' else 'incoming_voice_call' end,
    case when with_video then 'مكالمة فيديو واردة' else 'مكالمة صوتية واردة' end,
    case when with_video then 'Incoming video call' else 'Incoming voice call' end,
    caller_name || case when with_video then ' يتصل بك عبر الفيديو' else ' يتصل بك صوتيًا' end,
    caller_name || case when with_video then ' is video calling you' else ' is calling you' end,
    jsonb_build_object('room_id', target_room_id, 'conversation_id', target_conversation_id, 'caller_id', me, 'video', with_video),
    false
  ) returning id into notification_id;

  return notification_id;
end;
$$;
revoke execute on function public.start_direct_call(uuid, uuid, text, boolean) from public, anon;
grant execute on function public.start_direct_call(uuid, uuid, text, boolean) to authenticated;

